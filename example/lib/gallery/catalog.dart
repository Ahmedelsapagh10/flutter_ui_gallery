import 'package:flutter/material.dart';
import 'package:flutter_ui_gallery/flutter_ui_gallery.dart';

enum DesignCategory { sheets, dialogs, toasts, header, bottomNav }

enum DesignPurpose {
  quickActions,
  search,
  selection,
  confirmation,
  progress,
  navigation,
  feedback,
}

String purposeLabel(DesignPurpose purpose) => switch (purpose) {
  DesignPurpose.quickActions => 'Quick actions',
  DesignPurpose.search => 'Search',
  DesignPurpose.selection => 'Bulk selection',
  DesignPurpose.confirmation => 'Confirmation',
  DesignPurpose.progress => 'Task progress',
  DesignPurpose.navigation => 'Navigation',
  DesignPurpose.feedback => 'Status and feedback',
};

class SurfaceDesign {
  const SurfaceDesign(
    this.name,
    this.category,
    this.tagline,
    this.useCase,
    this.icon, {
    this.sheet,
    this.dialog,
    this.toast,
    this.appBar,
    this.bottomNav,
    required this.motion,
  });
  final String name, tagline, useCase, motion;
  final DesignCategory category;
  final IconData icon;
  final UiGallerySheetPreset? sheet;
  final UiGalleryDialogPreset? dialog;
  final UiGalleryToastPreset? toast;
  final UiGalleryAppBarPreset? appBar;
  final UiGalleryBottomNavPreset? bottomNav;
  String get id =>
      '${category.name}.${sheet?.name ?? dialog?.name ?? toast?.name ?? appBar?.name ?? bottomNav!.name}';
  DesignPurpose get purpose {
    if (bottomNav != null) return DesignPurpose.navigation;
    if (appBar == UiGalleryAppBarPreset.selectionBar) {
      return DesignPurpose.selection;
    }
    if (const {
      UiGalleryAppBarPreset.searchSwitch,
      UiGalleryAppBarPreset.focusBar,
    }.contains(appBar)) {
      return DesignPurpose.search;
    }
    if (toast == UiGalleryToastPreset.progressCard ||
        const {
          UiGalleryDialogPreset.timeline,
          UiGalleryDialogPreset.milestone,
        }.contains(dialog)) {
      return DesignPurpose.progress;
    }
    if (toast != null ||
        const {
          UiGalleryDialogPreset.spotlight,
          UiGalleryDialogPreset.statusBeacon,
        }.contains(dialog)) {
      return DesignPurpose.feedback;
    }
    if (dialog == UiGalleryDialogPreset.commandPalette || sheet != null) {
      return DesignPurpose.quickActions;
    }
    if (dialog != null) return DesignPurpose.confirmation;
    return DesignPurpose.navigation;
  }

  bool get recommended => const {
    'sheets.orbit',
    'dialogs.halo',
    'dialogs.commandPalette',
    'toasts.signal',
    'toasts.progressCard',
    'header.searchSwitch',
    'header.selectionBar',
    'bottomNav.adaptiveMinimal',
  }.contains(id);
}

